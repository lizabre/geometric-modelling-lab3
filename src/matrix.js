// Формула (11): зсув
export function translateMatrix(dx, dy) {
  return [
    [1, 0, 0],
    [0, 1, 0],
    [dx, dy, 1],
  ];
}

// Формула (12): обертання навколо довільної точки p, кут у градусах.
export function rotateAbout(px, py, angleDeg) {
  const a = (angleDeg * Math.PI) / 180;
  const c = Math.cos(a);
  const s = Math.sin(a);
  const tx = -px * (c - 1) + py * s; // -px * (cos(a) -1) + py * sin(a)
  const ty = -px * s - py * (c - 1); // -px  * sin(a) - py * (cos(a) -1)
  return [
    [c, s, 0],
    [-s, c, 0],
    [tx, ty, 1],
  ];
}
